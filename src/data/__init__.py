"""WORK-022: data governance, privacy and recourse (public boundary).

Owned surface: ``src/data`` — declared data policies (typed references
to governance-declared policy identifiers; fail closed on unknown ids —
the module never invents legal rules, it records and enforces declared
policy), disclosure with data minimization, commitment-based selective
disclosure over isolated datasets, policy-driven retention bookkeeping
(append-only; retention records state, they never rewrite or delete
financial history — constitution invariant 17), and the case/claim/
recourse lifecycle (typed disputes, investigations, decisions and
compiled refund/reversal packages recorded with explicit references —
no ledger authority: actual financial execution belongs to other
domains).

Public boundary: typed and versioned (``DATA_API_VERSION``). Consumed
domains, all merged at the implementation base: ``src.core`` (envelope,
single error authority, canonical hashing), ``src.transition`` (the one
state-transition kernel), ``src.trust`` (principals: who may request,
approve and act), ``src.evidence`` (observations and attestations:
provenance for investigations and decisions).

Registry discipline (frozen ``spec/registry/protocol-registry.json``,
never edited): no data/privacy/recourse event namespace exists, so all
lifecycle events emitted through the kernel use the existing frozen
``governance`` namespace; no ``payswap/data-policy/v1`` object type
exists, so every durable object kind uses an internal non-registry
``data/...`` format; command types are internal free-form strings per
the W026 sibling convention.
"""

